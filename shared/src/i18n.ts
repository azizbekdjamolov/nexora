export type Messages = (typeof messages)["en"];
export type MessageKey = {
  [K in keyof Messages]: Messages[K] extends string
    ? K
    : `${K & string}.${Extract<keyof Messages[K], string>}`;
}[keyof Messages];

export function getMessages(lang: Lang): Messages {
  return (messages[lang] ?? messages.en) as unknown as Messages;
}

export function translate(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  const dict = getMessages(lang);
  const parts = key.split(".");
  let value: unknown = dict;
  for (const part of parts) {
    if (value && typeof value === "object" && part in value) {
      value = (value as Record<string, unknown>)[part];
    } else {
      return key;
    }
  }
  if (typeof value !== "string") return key;
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m
  );
}